#!/usr/bin/env python3
"""Generate the kernel-track (decide +kernel) certificate modules Poincare11a/CertK/*.lean.

Usage: python3 -I export_certk.py CERT.json PROJECTDIR [LEAVES_PER_MODULE]

Reads the same frozen certificate as export_lean.py (same quadtree recursion, same leaf numbering) and writes:
  CertK/Part.lean       partOK ivs = true
  CertK/LibS<r>.lean    libS<r>.allPos = true (16 shards)
  CertK/Lib.lean        lib.allPos = true (assembled from the shards)
  CertK/Out.lean        outsideOK l i k = true for the 149 outside squares
  CertK/Leaf<g>.lean    checkLeaf lib ivs l i k R runs_<n> = true, LEAVES_PER_MODULE leaves per module
  CertK/Tree.lean       tree.OK lib ivs 0 0 0, a proof term mirroring the quadtree
All checks are `decide +kernel`; the shard modules import only Poincare11a.Checker and Poincare11a.Data.* (core Lean).
"""
import sys, json, os

CERT, ROOT = sys.argv[1], sys.argv[2]
PER = int(sys.argv[3]) if len(sys.argv) > 3 else 10
cert = json.load(open(CERT))
man = json.load(open(os.path.join(ROOT, 'Poincare11a', 'Data', 'manifest.json')))
OUT = os.path.join(ROOT, 'Poincare11a', 'CertK')
os.makedirs(OUT, exist_ok=True)

leafinfo = {tuple(code): (n_, R) for n_, code, R, _ in man['leaves']}
outcodes = sorted({tuple(c) for c in cert['outside']})
assert set(leafinfo) == {tuple(c) for c, _ in cert['leaves']}

HDR = '/- Generated by gen/export_certk.py. Do not edit. -/\n'
IMP_DATA = 'import Poincare11a.Data.Lib\nimport Poincare11a.Data.Ivl\nimport Poincare11a.Data.Leaves\n'
OPEN = 'namespace Poincare11a.CertK\nopen Poincare11a.Cert Poincare11a.Data\n\nset_option maxRecDepth 100000\n\n'


def write(name, body, imports=IMP_DATA):
    with open(os.path.join(OUT, name + '.lean'), 'w') as f:
        f.write(HDR + imports + '\n' + OPEN + body + '\nend Poincare11a.CertK\n')


write('Part', 'theorem ivs_partOK : partOK ivs = true := by decide +kernel\n')
for r in range(16):
    write(f'LibS{r}', f'theorem libS{r}_allPos : libS{r}.allPos = true := by decide +kernel\n',
          'import Poincare11a.Data.Lib\n')
body = 'theorem lib_allPos : lib.allPos = true := by\n  simp only [lib, LibT.allPos, ' + \
    ', '.join(f'libS{r}_allPos' for r in range(16)) + ', Bool.and_self]\n'
write('Lib', body, ''.join(f'import Poincare11a.CertK.LibS{r}\n' for r in range(16)))

ob = ''
outname = {}
for t, (l, i, k) in enumerate(outcodes):
    outname[(l, i, k)] = f'out_{t}'
    ob += f'theorem out_{t} : outsideOK {l} {i} {k} = true := by decide +kernel\n'
write('Out', ob)

leaves = sorted(leafinfo.items(), key=lambda kv: kv[1][0])
groups = [leaves[g:g + PER] for g in range(0, len(leaves), PER)]
for g, grp in enumerate(groups):
    b = ''
    for (l, i, k), (n_, R) in grp:
        b += f'theorem leaf_{n_} : checkLeaf lib ivs {l} {i} {k} {R} runs_{n_} = true := by decide +kernel\n'
    write(f'Leaf{g:02d}', b)


def proof(l, i, k):
    c = (l, i, k)
    if c in leafinfo:
        return f'leaf_{leafinfo[c][0]}'
    if c in outname:
        return outname[c]
    ch = [proof(l + 1, 2 * i + a, 2 * k + b) for a in (0, 1) for b in (0, 1)]
    return '⟨' + ', '.join(ch) + '⟩'


body = 'theorem tree_OK : tree.OK lib ivs 0 0 0 :=\n  ' + proof(0, 0, 0) + '\n'
write('Tree', body, IMP_DATA + 'import Poincare11a.CertK.Out\n' +
      ''.join(f'import Poincare11a.CertK.Leaf{g:02d}\n' for g in range(len(groups))))
print('groups', len(groups), 'leaves', len(leaves), 'outside', len(outcodes))
