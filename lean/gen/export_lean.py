#!/usr/bin/env python3
"""Generate the Lean data of the 11a certificate from the frozen JSON (read-only input).

Usage: python3 -I export_lean.py CERT.json OUTDIR

Writes OUTDIR/Lib.lean, OUTDIR/Ivl.lean, OUTDIR/Leaves.lean (namespace Poincare11a.Data) and OUTDIR/manifest.json.
Taken unchanged from the certificate: the polynomials (only the used ones, in increasing original index), the quadtree of
leaf and outside squares, and the polynomial index of every (leaf, theta-interval), run-length encoded.
Derived: the theta-partition t_i = T_i/2^32 ~ tan(i*pi/4096), the outward-rounded v-range and the rounded-down weights of
each interval, and R/2^60 >= s1^(3/2) for each leaf. Every derived inequality is re-checked here and in Lean.
"""
import sys, json, math, os, hashlib
from fractions import Fraction as F

CERT, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
raw = open(CERT, 'rb').read()
cert = json.loads(raw)
N = cert['N']
assert N == 1024 and cert['claimed'] == '71/50'

DLIB = 2 ** 40 * 5 ** 8
VSC = 2 ** 40
P60, P64, P32 = 2 ** 60, 2 ** 64, 2 ** 32

# ---- library: used polynomials, integer scaled ----
used = sorted({j for _, idx in cert['leaves'] for j in idx if j >= 0})
newidx = {j: t for t, j in enumerate(used)}
lib = []
for j in used:
    co = [F(x) for x in cert['library'][j]]
    ints = []
    for x in co:
        y = x * DLIB
        assert y.denominator == 1, (j, x)
        ints.append(int(y))
    lib.append(tuple(ints))


def libtree(items):
    if len(items) == 0:
        return 'LibT.nil'
    if len(items) == 1:
        A, B, C, D = items[0]
        return f'LibT.leaf ⟨{A}, {B}, {C}, {D}⟩'
    return f'LibT.node ({libtree(items[0::2])}) ({libtree(items[1::2])})'


def lookup(items, j):  # mirror of LibT.get
    if len(items) == 0:
        return None
    if len(items) == 1:
        return items[0] if j == 0 else None
    return lookup(items[0::2], j // 2) if j % 2 == 0 else lookup(items[1::2], j // 2)


for t in range(len(lib)):
    assert lookup(lib, t) == lib[t]

# ---- partition ----
T = [0] + [int(round(math.tan(i * math.pi / (4 * N)) * P32)) for i in range(1, N)] + [P32]
assert all(T[i] < T[i + 1] for i in range(N))
ivs = []
for i in range(N):
    TL, TR = T[i], T[i + 1]
    cl, pl = P64 - TL * TL, P64 + TL * TL
    cr, pr = P64 - TR * TR, P64 + TR * TR
    VL = (4 * VSC * pl * pl) // (cl * cl)
    assert VL * cl * cl <= 4 * VSC * pl * pl
    if TR < P32:
        VH = -((-4 * VSC * pr * pr) // (cr * cr))
        assert 4 * VSC * pr * pr <= VH * cr * cr
    else:
        VH = VL
    num = P64 * 2 * P32 * (TR - TL) * (P64 + TL * TR)
    LL = num // (pl * pr)
    assert 0 <= LL and LL * pl * pr <= num
    w = lambda V: ((V - 6 * VSC) * VSC, (V - 4 * VSC) * VSC, V * V - 30 * VSC * V + 120 * VSC * VSC)
    ivs.append((TL, TR, VL, VH, LL) + w(VL) + w(VH))

# ---- leaves ----
leafcodes = {tuple(code): idx for code, idx in cert['leaves']}
outcodes = {tuple(code) for code in cert['outside']}
assert not (set(leafcodes) & outcodes)


def Rbound(l, i):
    S1 = (i + 1) * 2 ** (60 - l)
    R = math.isqrt(-(-S1 ** 3 // P60))
    while R * R * P60 < S1 ** 3:
        R += 1
    return R


leafnames = {}
leafdefs = []
for n_, code in enumerate(sorted(leafcodes)):
    idx = leafcodes[code]
    runs = []
    for v in idx:
        nv = newidx[v] if v >= 0 else -1
        if runs and runs[-1][0] == nv:
            runs[-1][1] += 1
        else:
            runs.append([nv, 1])
    assert runs[-1][0] == -1, code
    l, i, k = code
    leafnames[code] = (f'runs_{n_}', Rbound(l, i))
    leafdefs.append((n_, code, runs))

visited = set()


def qt(l, i, k):
    c = (l, i, k)
    if c in leafcodes:
        visited.add(c)
        nm, R = leafnames[c]
        return f'QT.leaf {R} {nm}'
    if c in outcodes:
        visited.add(c)
        return 'QT.out'
    assert l < 40
    ch = [qt(l + 1, 2 * i + a, 2 * k + b) for a in (0, 1) for b in (0, 1)]
    return 'QT.node ' + ' '.join(f'({x})' for x in ch)


treestr = qt(0, 0, 0)
assert visited == set(leafcodes) | outcodes

HDR = '/- Generated by gen/export_lean.py from {} (sha256 {}). Do not edit. -/\n'.format(
    os.path.basename(CERT), hashlib.sha256(raw).hexdigest())

LIBD = 4  # the top LIBD levels of the library tree are split into 2^LIBD named shards (kernel track)


def libtop(prefix, d):
    if d == LIBD:
        return f'libS{prefix}'
    return f'LibT.node ({libtop(prefix, d + 1)}) ({libtop(prefix + 2 ** d, d + 1)})'


with open(os.path.join(OUT, 'Lib.lean'), 'w') as f:
    f.write(HDR + 'import Poincare11a.Checker\n\nnamespace Poincare11a.Data\nopen Poincare11a.Cert\n\nset_option maxRecDepth 100000\n\n')
    for r in range(2 ** LIBD):
        f.write(f'/-- Library shard {r}: the polynomials with index ≡ {r} mod {2 ** LIBD}. -/\n')
        f.write(f'def libS{r} : LibT :=\n  ' + libtree(lib[r::2 ** LIBD]) + '\n\n')
    f.write(f'/-- The {len(lib)} library polynomials used by the certificate, scaled by DLIB. -/\n')
    f.write('def lib : LibT :=\n  ' + libtop(0, 0) + '\n\nend Poincare11a.Data\n')
# the sharded tree is the same term as libtree(lib) (checked here by structural comparison)
assert all(len(lib[r::2 ** LIBD]) > 1 for r in range(2 ** LIBD))


def libtree_sh(items, prefix, d):
    if d == LIBD:
        return libtree(items)
    return f'LibT.node ({libtree_sh(items[0::2], prefix, d + 1)}) ({libtree_sh(items[1::2], prefix + 2 ** d, d + 1)})'


assert libtree_sh(lib, 0, 0) == libtree(lib)

CH = 128
with open(os.path.join(OUT, 'Ivl.lean'), 'w') as f:
    f.write(HDR + 'import Poincare11a.Checker\n\nnamespace Poincare11a.Data\nopen Poincare11a.Cert\n\n')
    for c in range(N // CH):
        f.write(f'def ivs{c} : List Ivl := [\n')
        rows = ['  ⟨' + ', '.join(str(x) for x in ivs[r]) + '⟩' for r in range(c * CH, (c + 1) * CH)]
        f.write(',\n'.join(rows) + ']\n\n')
    f.write('/-- The θ-partition table (1024 intervals). -/\n')
    f.write('def ivs : List Ivl := ' + ' ++ '.join(f'ivs{c}' for c in range(N // CH)) + '\n\nend Poincare11a.Data\n')

with open(os.path.join(OUT, 'Leaves.lean'), 'w') as f:
    f.write(HDR + 'import Poincare11a.Checker\n\nnamespace Poincare11a.Data\nopen Poincare11a.Cert\n\n')
    for n_, code, runs in leafdefs:
        f.write(f'/-- leaf {code} -/\ndef runs_{n_} : List (Int × Nat) := [' +
                ', '.join(f'({a}, {b})' for a, b in runs) + ']\n')
    f.write('\n/-- The quadtree of leaf and outside squares. -/\ndef tree : QT :=\n  ' + treestr + '\n\nend Poincare11a.Data\n')

man = {'cert_sha256': hashlib.sha256(raw).hexdigest(), 'used': used,
       'leaves': [[n_, list(code), leafnames[code][1], len(runs)] for n_, code, runs in leafdefs]}
json.dump(man, open(os.path.join(OUT, 'manifest.json'), 'w'))
print('lib', len(lib), 'leaves', len(leafdefs), 'outside', len(outcodes), 'runs', sum(len(r) for _, _, r in leafdefs))

# ---- integer mirror of Poincare11a.Cert.checkLeaf / posOK (sanity check of the generated data) ----
ONE = DLIB * VSC * VSC * P60


def sel(w, lo, hi):
    return w * hi if w >= 0 else w * lo


def check_leaf(code, runs, R):
    l, i, k = code
    sh = 2 ** (60 - l)
    S0, S1 = i * sh, (i + 1) * sh
    T0 = max(k * sh, i * i * 2 ** (60 - 2 * l))
    T1 = min((k + 1) * sh, R)
    assert l <= 30 and S1 ** 3 <= R * R * P60
    g, pos = 0, 0
    for j, ln in runs:
        if j >= 0:
            A, B, C, D = lib[j]
            e = C + 15 * D
            c3 = 10 * D * S1
            k0 = (A + B + 3 * C + 15 * D) * VSC * VSC * P60
            c4 = sorted([e * S0, e * S1]); c3r = sorted([0, c3]); c6 = sorted([D * T0, D * T1])
            for t in range(pos, pos + ln):
                iv = ivs[t]
                el = k0 + sel(iv[5], *c4) + sel(iv[6], *c3r) + sel(iv[7], *c6)
                eh = k0 + sel(iv[8], *c4) + sel(iv[9], *c3r) + sel(iv[10], *c6)
                g += iv[4] * (ONE - min(ONE, max(el, eh)))
        pos += ln
    assert pos == N
    return g


worst = None
for n_, code, runs in leafdefs:
    g = check_leaf(code, runs, leafnames[code][1])
    assert 1507965 * P64 * ONE <= g * 10 ** 7, code
    tot = F(15707965, 10 ** 7) - F(g, P64 * ONE)
    if worst is None or tot > worst[0]:
        worst = (tot, code)
print('integer mirror: all leaves pass; worst leaf total', float(worst[0]), worst[1])
